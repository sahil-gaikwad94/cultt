/**
 * supabase/migrations/0009_seed.sql generator.
 *
 *   node scripts/build-seed-sql.mjs
 *
 * The database needs real `style_vec` / `embedding` values for the Resonance
 * Engine to rank anything. Those vectors are produced by the SAME functions the
 * running app uses (`memeStyleVector`, `trackEmbedding`), loaded here through
 * esbuild, rather than by re-implementing the taxonomy in SQL. One source of
 * truth: a tag added to the taxonomy changes the client and the seed together,
 * and cannot silently drift apart.
 *
 * The output is committed so a deploy never depends on this script having run.
 */

import { build } from 'esbuild';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const tmp = resolve(root, 'node_modules/.cache/cultured');

/** Loads the real TypeScript modules as ESM so the seed uses the real functions. */
async function loadEngine() {
  mkdirSync(tmp, { recursive: true });
  const entry = resolve(tmp, 'seed-entry.ts');
  writeFileSync(
    entry,
    `export { memeStyleVector, trackEmbedding } from ${JSON.stringify(
      resolve(root, 'src/lib/matching/embed.ts'),
    )}
     export { SEED_TRACKS } from ${JSON.stringify(resolve(root, 'src/data/seed/tracks.ts'))}`
  );
  const out = resolve(tmp, 'seed-entry.mjs');
  await build({
    entryPoints: [entry],
    outfile: out,
    bundle: true,
    format: 'esm',
    platform: 'node',
    logLevel: 'silent',
  });
  return import(pathToFileURL(out).href);
}

/** pgvector's text literal. Cheaper and more legible than a function call. */
const vec = (values) =>
  `'[${values.map((v) => (Number.isFinite(v) ? v.toFixed(6) : '0')).join(',')}]'::vector`;

/** Single-quote escaping, and a refusal to emit a string that could break out. */
const q = (value) => {
  const text = value == null ? '' : String(value);
  if (text.includes('\u0000')) throw new Error('NUL byte in seed text');
  return `'${text.replace(/'/g, "''")}'`;
};

const arr = (values) =>
  values && values.length
    ? `array[${values.map((v) => q(v)).join(', ')}]::text[]`
    : `'{}'::text[]`;

const { memeStyleVector, trackEmbedding, SEED_TRACKS } = await loadEngine();

const corpus = JSON.parse(readFileSync(resolve(root, 'src/data/seed/memes.json'), 'utf8'));
const memes = corpus.memes ?? corpus;

if (!Array.isArray(memes) || memes.length === 0) throw new Error('empty meme corpus');
if (!Array.isArray(SEED_TRACKS) || SEED_TRACKS.length === 0) throw new Error('no seed tracks');

const lines = [];
lines.push(
  '-- 0009_seed.sql — GENERATED by scripts/build-seed-sql.mjs. Do not edit by hand.',
  '--',
  `-- ${memes.length} original memes and ${SEED_TRACKS.length} original tracks. Every caption,`,
  '-- alt text and track is written for cultured; nothing here is a real-world',
  '-- catalogue entry or a licensed work, so the feed ships without a clearance.',
  '--',
  '-- Vectors come from the same embedding functions the app runs, so the',
  '-- database and the client can never disagree about what a tag means.',
  '--',
  '-- Re-runnable: `slug` is unique on both tables and every insert upserts.',
  '',
  '-- ------------------------------------------------------------------ memes',
  '',
  'insert into memes (slug, source, caption_text, alt_text, style_vec, categories,',
  '                   topic, bg, fg, ac, likes, laughs, license_meta, status)',
  'values'
);

const memeRows = memes.map((meme) => {
  const tags = [...(meme.tags ?? [])];
  const vector = memeStyleVector({ tags, styles: meme.styles });
  const categories = meme.content ?? [];
  return [
    '  (',
    [
      q(meme.id),
      q('pack'),
      q(meme.text),
      q(meme.alt),
      vec(vector),
      arr(categories),
      q(meme.topic ?? 'all'),
      q(meme.bg ?? '#EFE9DA'),
      q(meme.fg ?? '#141413'),
      q(meme.ac ?? '#F26B4E'),
      String(Number.isFinite(meme.likes) ? Math.max(0, Math.trunc(meme.likes)) : 0),
      String(Number.isFinite(meme.laughs) ? Math.max(0, Math.trunc(meme.laughs)) : 0),
      q(JSON.stringify({ origin: 'cultured-original', generated: true })),
      q(meme.status ?? 'live'),
    ].join(', '),
    ')',
  ].join('');
});

lines.push(memeRows.join(',\n'));
lines.push(
  'on conflict (slug) do update set',
  '  caption_text = excluded.caption_text,',
  '  alt_text = excluded.alt_text,',
  '  style_vec = excluded.style_vec,',
  '  categories = excluded.categories,',
  '  topic = excluded.topic,',
  '  bg = excluded.bg, fg = excluded.fg, ac = excluded.ac,',
  '  status = excluded.status;',
  '',
  '-- ----------------------------------------------------------------- tracks',
  '',
  '-- No audio is stored or re-streamed. preview_url stays null until the',
  '-- PreviewProvider resolves a legal 30s clip and caches it here (brief §2.2).',
  '',
  'insert into tracks (slug, title, artist, genres, length_seconds, blurb, style, embedding)',
  'values'
);

const trackRows = SEED_TRACKS.map((track) => {
  const vector = trackEmbedding({
    title: track.title,
    artist: track.artist,
    genres: track.genres,
  });
  return [
    '  (',
    [
      q(track.id),
      q(track.title),
      q(track.artist),
      arr(track.genres),
      String(Math.max(0, Math.trunc(track.length))),
      q(track.blurb),
      q(track.style ?? 'dusk'),
      vec(vector),
    ].join(', '),
    ')',
  ].join('');
});

lines.push(trackRows.join(',\n'));
lines.push(
  'on conflict (slug) do update set',
  '  title = excluded.title,',
  '  artist = excluded.artist,',
  '  genres = excluded.genres,',
  '  length_seconds = excluded.length_seconds,',
  '  blurb = excluded.blurb,',
  '  style = excluded.style,',
  '  embedding = excluded.embedding;',
  '',
  '-- ------------------------------------------------------------ daily drops',
  '',
  '-- The Daily Drop is one meme + one track per day, written here for the first',
  '-- fortnight so the arrival ceremony has something to arrive with. A scheduled',
  '-- job extends this; the table is the contract either way.',
  'insert into daily_drops (day, meme_id, track_id, hint)',
  'select d.day,',
  '       (select m.id from memes m order by md5(d.day::text || m.slug) limit 1),',
  '       (select t.id from tracks t order by md5(d.day::text || t.slug) limit 1),',
  '       $hint$Today\'s drop. No spoilers.$hint$',
  'from (',
  '  select generate_series(current_date, current_date + 13, interval \'1 day\')::date as day',
  ') d',
  'where exists (select 1 from memes) and exists (select 1 from tracks)',
  'on conflict (day) do nothing;',
  ''
);

writeFileSync(resolve(root, 'supabase/migrations/0009_seed.sql'), lines.join('\n'));

// The RPCs that the client contract calls but that are not part of the engine
// file get their own migration, so a review can read them separately.
console.log(
  `wrote supabase/migrations/0009_seed.sql — ${memes.length} memes, ${SEED_TRACKS.length} tracks`
);
